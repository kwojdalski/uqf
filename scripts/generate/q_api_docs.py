#!/usr/bin/env python3
"""Render the q API reference - docs/reference/q-api/ - from the qDoc comments.

    qDoc comments in src/**/*.q
            |  docs/man.q reads them (run by export_api_reference.q)
            v
    one Markdown page per module, and an index
            |
            v
    the Quarto site, which runs this as its pre-render step

No second comment parser: the records are the ones docs/man.q registers, and
this file only lays them out. It never infers a signature the comments do not
state, and never runs an example - tests/q/test_docstring_examples.q and
tests/q/run_examples.q do that.

BUILT, NEVER COMMITTED. docs/reference/q-api/ is gitignored and belongs to
this script: each run writes the whole set and removes any page in it the set
no longer has, and touches nothing outside it. Committing the pages would
make every docstring edit a regeneration, and every two branches that touch
one a merge conflict in files nobody wrote - the shape docs/man.q dropped
when it stopped being generated. The cost is that rendering the site needs a
q: $QCMD, else `q` on PATH. In CI that is the pinned PeachQ.

THE SNAPSHOT IS THE GIT INDEX. The q files documented are the tracked ones,
as staged, checked out into a scratch directory - never the working tree,
where an installed sidecar bundle adds untracked q under src/ and its own
blocks inside tracked files. Stage an edit to see it here.

FAILS RATHER THAN PUBLISH LESS. A q that does not load the reader, a name
documented twice, an entry with two @return lines or one parameter twice, a
record with no source file, and a page or link that does not come out of the
render exactly once each stop the run with the reason.

Standard library only: the documentation jobs run it under a bare python3.

Usage:
    python3 scripts/generate/q_api_docs.py            # write docs/reference/q-api/
    python3 scripts/generate/q_api_docs.py --out DIR  # somewhere else
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import string
import subprocess
import sys
import tempfile
from collections import defaultdict
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "docs" / "reference" / "q-api"
EXPORTER = REPO / "scripts" / "generate" / "export_api_reference.q"
READER = "docs/man.q"
LEDGER = "src/etl/installed_bundles.json"

#: The first line of every page this script writes. A file in the output
#: directory without it was not written here, and is never deleted.
MARKER = "<!-- generated by scripts/generate/q_api_docs.py from the qDoc comments; do not edit -->"


class GenerationError(Exception):
    """The reference would be incomplete or ambiguous; nothing is written."""


@dataclass
class Entry:
    fullname: str
    ns: str
    file: str
    description: str
    params: list[tuple[str, str]] = field(default_factory=list)
    returns: list[str] = field(default_factory=list)
    throws: list[str] = field(default_factory=list)
    examples: list[str] = field(default_factory=list)

    @property
    def anchor(self) -> str:
        """`.qf.px.fwd_simple` -> `qf.px.fwd_simple`: the qualified name, which
        is unique and needs no slug rules to predict."""
        return self.fullname.lstrip(".")


@dataclass
class Module:
    file: str
    namespaces: list[str]
    header: str
    entries: list[Entry] = field(default_factory=list)

    @property
    def page(self) -> str:
        """src/pricing/cross.q -> src/pricing/cross.md: the full relative path,
        so src/pricing/cross.q and src/etl/streaming/cross.q cannot meet."""
        return str(PurePosixPath(self.file).with_suffix(".md"))


# ----------------------------------------------------------------- snapshot


def git(*args: str, cwd: Path = REPO, stdin: bytes | None = None) -> bytes:
    result = subprocess.run(["git", *args], cwd=cwd, input=stdin, capture_output=True, check=False)
    if result.returncode != 0:
        raise GenerationError(
            f"git {' '.join(args)} failed: {result.stderr.decode(errors='replace').strip()}"
        )
    return result.stdout


def snapshot_files() -> list[str]:
    """The tracked q sources the reference documents, and the reader itself."""
    tracked = git("ls-files", "-z", "--", "src", READER).decode().split("\0")
    files = sorted(p for p in tracked if p == READER or (p.startswith("src/") and p.endswith(".q")))
    if READER not in files:
        raise GenerationError(f"{READER} is not tracked - there is no reader to run")
    ledger = REPO / LEDGER
    if ledger.is_file():
        try:
            entries = json.loads(ledger.read_text())
        except ValueError as exc:
            raise GenerationError(f"{LEDGER} is not JSON ({exc})") from None
        installed = {f for e in entries.values() for f in e.get("files", {})}
        staged = sorted(installed & set(files))
        if staged:
            raise GenerationError(
                "these files were installed by a sidecar bundle and are staged in git, "
                "so they would be published as this tree's API: " + ", ".join(staged)
            )
    return files


def checkout(files: list[str], dest: Path) -> None:
    """The staged content of `files`, written under `dest`."""
    git("checkout-index", "-z", "--stdin", f"--prefix={dest}/", stdin="\0".join(files).encode())


# ----------------------------------------------------------------- reading


def q_command() -> tuple[str, dict[str, str]]:
    """$QCMD, else `q` on PATH - the rule scripts/test.py and uqs follow."""
    env = os.environ.copy()
    name = env.get("QCMD") or "q"
    exe = shutil.which(name)
    if exe is None:
        raise GenerationError(
            f"no q interpreter: {name!r} is not runnable. Set $QCMD to a q - KDB-X, or "
            "the pinned PeachQ that `python3 scripts/peachq.py` prints - or put q on PATH."
        )
    env.setdefault("QHOME", str(Path.home() / ".kx"))
    return exe, env


def export(root: Path) -> dict:
    """Run the reader over the snapshot at `root` and return its records."""
    exe, env = q_command()
    out = root / "api_reference.json"
    result = subprocess.run(
        [exe, str(EXPORTER), str(out), "-q"],
        cwd=root,
        env=env,
        stdin=subprocess.DEVNULL,
        capture_output=True,
        timeout=300,
        check=False,
    )
    if result.returncode != 0 or not out.is_file():
        raise GenerationError(
            f"the q reader failed ({exe}, exit {result.returncode}):\n"
            f"{result.stdout.decode(errors='replace')}{result.stderr.decode(errors='replace')}"
        )
    try:
        return json.loads(out.read_text())
    except ValueError as exc:
        raise GenerationError(f"the q reader did not write JSON: {exc}") from None


def as_text(value) -> str:
    """q writes a one-character string as a bare string and an empty one as
    "", but a list it could not type as a list; normalise to str."""
    if isinstance(value, list):
        return "".join(value)
    return value


def modules_from(records: dict, sources: list[str]) -> list[Module]:
    """Group the registry into modules, refusing anything ambiguous."""
    problems: list[str] = []
    known = set(sources)
    modules: dict[str, Module] = {}
    for row in records["files"]:
        path = as_text(row["file"])
        if path in modules:
            problems.append(f"{path} was read twice")
        modules[path] = Module(
            file=path,
            namespaces=[n for n in as_text(row["namespaces"]).split("|") if n],
            header=as_text(row["header"]),
        )

    entries: dict[str, Entry] = {}
    skipped: set[str] = set()  # already reported; their args would only repeat it
    for row in records["funcs"]:
        name, path = as_text(row["fullname"]), as_text(row["file"])
        if path not in known:
            problems.append(
                f"{name}: read from {path or '(no file)'}, which is not in the snapshot"
            )
            skipped.add(name)
            continue
        if path not in modules:
            problems.append(f"{name}: {path} has no module record")
            skipped.add(name)
            continue
        if name in entries:
            problems.append(
                f"{name} is documented in both {entries[name].file} and {path} - "
                "one name, one documented definition"
            )
            continue
        entry = Entry(name, as_text(row["ns"]), path, as_text(row["description"]))
        entries[name] = entry
        modules[path].entries.append(entry)

    for row in records["args"]:
        name, tag = as_text(row["fullname"]), as_text(row["tag"])
        text = as_text(row["description"])
        entry = entries.get(name)
        if entry is None:
            if name not in skipped:
                problems.append(f"{name}: a documented {tag} for a name the registry does not have")
            continue
        if tag == "param":
            entry.params.append((as_text(row["param"]), text))
        elif tag == "return":
            entry.returns.append(text)
        elif tag == "throws":
            entry.throws.append(text)
        elif tag == "eg":
            entry.examples.append(text)
        else:
            problems.append(f"{name}: unknown tag {tag!r}")

    private = {as_text(p) for p in records["private"]}
    for name, entry in entries.items():
        if name in private:
            problems.append(f"{name} is tagged @private and documented as API")
        if len(entry.returns) > 1:
            problems.append(f"{name} ({entry.file}) has {len(entry.returns)} @return lines")
        seen = [p for p, _ in entry.params]
        twice = sorted({p for p in seen if seen.count(p) > 1})
        if twice:
            problems.append(
                f"{name} ({entry.file}) documents @param {', '.join(twice)} more than once"
            )

    if not entries:
        problems.append("the reader registered no documented names at all")
    if problems:
        raise GenerationError(
            "the q API reference would be incomplete or ambiguous:\n  " + "\n  ".join(problems)
        )
    return [modules[k] for k in sorted(modules) if modules[k].entries]


# ----------------------------------------------------------------- Markdown

#: Every ASCII punctuation character may be backslash-escaped in Pandoc's
#: Markdown, and the comments are prose with q in it - a lone backtick
#: before a symbol, `$`, `@`, `*`, `_`, `<` - so all of it is escaped and the
#: text renders as written.
_PUNCT = set(string.punctuation)


def text(s: str) -> str:
    return "".join("\\" + c if c in _PUNCT else c for c in s)


def paragraphs(s: str) -> str:
    return "\n\n".join(text(p) for p in s.split("\n") if p.strip())


def code(s: str) -> str:
    """Inline code that survives backticks of its own."""
    run = longest_run(s, "`")
    fence = "`" * (run + 1)
    pad = " " if s.startswith("`") or s.endswith("`") else ""
    return f"{fence}{pad}{s}{pad}{fence}"


def code_block(s: str) -> str:
    fence = "`" * max(3, longest_run(s, "`") + 1)
    return f"{fence}q\n{s}\n{fence}"


def longest_run(s: str, ch: str) -> int:
    best = cur = 0
    for c in s:
        cur = cur + 1 if c == ch else 0
        best = max(best, cur)
    return best


def yaml_string(s: str) -> str:
    return json.dumps(s)


def relative(from_page: str, to_page: str) -> str:
    return os.path.relpath(to_page, os.path.dirname(from_page) or ".").replace(os.sep, "/")


def render_entry(e: Entry) -> str:
    out = [f"### {code(e.fullname)} {{#{e.anchor}}}", ""]
    if e.description:
        out += [paragraphs(e.description), ""]
    if e.params:
        out += ["**Parameters**", ""]
        out += [f"- {code(p)}" + (f" --- {text(d)}" if d else "") for p, d in e.params]
        out.append("")
    if e.returns:
        out += [f"**Returns** {text(e.returns[0])}", ""]
    if e.throws:
        out += ["**Throws**", ""]
        out += [f"- {text(t)}" for t in e.throws]
        out.append("")
    if e.examples:
        out += ["**Examples**" if len(e.examples) > 1 else "**Example**", ""]
        for ex in e.examples:
            out += [code_block(ex), ""]
    return "\n".join(out)


def render_module(m: Module) -> str:
    out = [
        "---",
        f"title: {yaml_string(m.file)}",
        "---",
        "",
        MARKER,
        "",
    ]
    if m.header:
        out += [paragraphs(m.header), ""]
    ns = ", ".join(code(n) for n in m.namespaces)
    out += [
        f"Source {code(m.file)}"
        + (f", namespace{'s' if len(m.namespaces) > 1 else ''} {ns}" if ns else "")
        + f". {len(m.entries)} documented name{'s' if len(m.entries) != 1 else ''}; "
        f"[all modules]({relative(m.page, 'index.md')}).",
        "",
        "## API",
        "",
    ]
    out += [render_entry(e) for e in m.entries]
    return "\n".join(out).rstrip() + "\n"


def summary(e: Entry) -> str:
    first = e.description.split("\n")[0] if e.description else (e.returns[0] if e.returns else "")
    end = first.find(". ")
    return first[: end + 1] if end > 0 else first


def render_index(modules: list[Module]) -> str:
    total = sum(len(m.entries) for m in modules)
    out = [
        "---",
        'title: "q API"',
        "---",
        "",
        MARKER,
        "",
        f"Every documented q name under `src/`: {total} names in {len(modules)} modules, "
        "read from the qDoc comment above each definition. A module's page lists its "
        "names in source order; below, every name by namespace.",
        "",
        "## Modules",
        "",
        "| Module | Namespaces | Names |",
        "| --- | --- | --- |",
    ]
    for m in modules:
        ns = ", ".join(code(n) for n in m.namespaces)
        out.append(f"| [{code(m.file)}]({m.page}) | {ns} | {len(m.entries)} |")
    out.append("")
    out += ["## Names", ""]
    by_ns: dict[str, list[tuple[Entry, Module]]] = defaultdict(list)
    for m in modules:
        for e in m.entries:
            by_ns[e.ns].append((e, m))
    for ns in sorted(by_ns):
        out += [f"### {code(ns)}", ""]
        for e, m in sorted(by_ns[ns], key=lambda pair: pair[0].fullname):
            line = f"- [{code(e.fullname)}]({m.page}#{e.anchor})"
            gist = summary(e)
            out.append(line + (f" --- {text(gist)}" if gist else ""))
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def render(modules: list[Module]) -> dict[str, str]:
    """Every page, by path relative to the output directory."""
    pages = {m.page: render_module(m) for m in modules}
    if len(pages) != len(modules):
        raise GenerationError("two modules map to one page")
    pages["index.md"] = render_index(modules)
    verify(modules, pages)
    return pages


def verify(modules: list[Module], pages: dict[str, str]) -> None:
    """Each name anchored exactly once, and each index link landing on one."""
    anchors: dict[str, int] = defaultdict(int)
    for m in modules:
        for e in m.entries:
            anchors[f"{m.page}#{e.anchor}"] += pages[m.page].count(f"{{#{e.anchor}}}")
    bad = sorted(k for k, n in anchors.items() if n != 1)
    if bad:
        raise GenerationError("names not anchored exactly once: " + ", ".join(bad[:20]))
    index = pages["index.md"]
    missing = [k for k in anchors if f"]({k})" not in index]
    if missing:
        raise GenerationError("names the index does not link: " + ", ".join(sorted(missing)[:20]))


# ----------------------------------------------------------------- writing


def is_generated(path: Path) -> bool:
    with path.open(encoding="utf-8", errors="replace") as fh:
        return any(line.rstrip("\n") == MARKER for _, line in zip(range(10), fh, strict=False))


def sync(pages: dict[str, str], out: Path) -> tuple[int, int]:
    """Write `pages` under `out` and remove whatever else is there: a page the
    set no longer has, or what an interrupted render left beside one (Quarto
    writes its .html and *_files/ next to the source before moving them).
    A Markdown page this script did not write is refused, not deleted -
    someone authored it. Nothing outside `out` is touched.
    Returns (written, removed)."""
    out.mkdir(parents=True, exist_ok=True)
    authored = []
    stale = []
    for path in sorted(p for p in out.rglob("*") if p.is_file()):
        rel = path.relative_to(out).as_posix()
        if rel in pages:
            continue
        if path.suffix in (".md", ".qmd") and not is_generated(path):
            authored.append(rel)
        else:
            stale.append(path)
    if authored:
        raise GenerationError(
            f"{out} is this script's output directory, but holds pages it did not write: "
            + ", ".join(authored[:10])
            + " - move them out; nothing was changed"
        )
    for path in stale:
        path.unlink()
    for d in sorted((p for p in out.rglob("*") if p.is_dir()), key=lambda p: -len(p.parts)):
        if not any(d.iterdir()):
            d.rmdir()
    written = 0
    for rel, body in pages.items():
        path = out / rel
        if path.is_file() and path.read_text(encoding="utf-8") == body:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8")
        written += 1
    return written, len(stale)


def generate(out: Path = OUT) -> tuple[int, int, int, int]:
    """(modules, names, pages written, pages removed)."""
    files = snapshot_files()
    with tempfile.TemporaryDirectory(prefix="uqf-qapi-") as tmp:
        root = Path(tmp)
        checkout(files, root)
        records = export(root)
    modules = modules_from(records, [f for f in files if f != READER])
    pages = render(modules)
    written, removed = sync(pages, out)
    return len(modules), sum(len(m.entries) for m in modules), written, removed


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--out", type=Path, default=OUT, help="output directory (default: %(default)s)")
    args = ap.parse_args(argv)
    try:
        modules, names, written, removed = generate(args.out.resolve())
    except GenerationError as exc:
        print(f"q_api_docs: {exc}", file=sys.stderr)
        return 1
    print(
        f"q_api_docs: {names} names in {modules} modules; {written} page(s) written, "
        f"{removed} removed, in {args.out}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
