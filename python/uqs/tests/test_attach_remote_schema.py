"""Durable registration on a stack on another machine: the tickerplant appends
the block to its own schema file (`--remote-schema-file`, #1651).

The fake stack keeps the tickerplant's files apart from this machine's disk
(`FakeStack.stack_files`), at a path that does not exist here - so a test that
passes also shows the path was never opened on this machine.
"""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path

import pytest
from attach_support import FakeStack, make_bundle

from uqs.attach import config, detach, facts, persist, plan, service, verify, workflow
from uqs.attach.config import Attachment, AttachmentError
from uqs.attach.facts import Host
from uqs.attach.manifest import Manifest
from uqs.attach.remote import Endpoint
from uqs.attach.schema_files import RemoteFile
from uqs.paths import repo_root

ROOT = repo_root()
HERE = Host(lambda h, p: False, ("localhost",))
#: On the stack's machine; no such directory here.
STACK_PATH = "/srv/uat-box/torq/database.q"
STACK_TEXT = "quote:([] time:`timestamp$(); sym:`symbol$())\n"


class Publisher:
    def __init__(self) -> None:
        self.on = False

    def running(self, att) -> bool:
        return self.on

    def start(self, att) -> None:
        self.on = True

    def stop(self, att) -> None:
        self.on = False


@pytest.fixture(autouse=True)
def no_real_ports(monkeypatch):
    monkeypatch.setattr(facts, "_tcp_open", lambda host, port: False)


@pytest.fixture
def bundle(tmp_path: Path) -> Path:
    return make_bundle(tmp_path / "piggybank")


def _att(bundle: Path, **kw) -> Attachment:
    kw.setdefault("remote_schema_file", True)
    att = service.create(
        "pb-uat", "pb_general_ledger", bundle, 6000, ROOT, host="uat-box.example", **kw
    )
    return replace(att, publisher=replace(att.publisher, advertised_host="laptop.corp"))


def _fake() -> FakeStack:
    fake = FakeStack(6000)
    fake.remote_schema(STACK_PATH, STACK_TEXT)
    return fake


def _run(att: Attachment, fake: FakeStack, state: Path, publisher: Publisher | None = None):
    resolved = workflow.Resolved(att, "new", config.directory(att.name, state))
    shown = plan.build(att, fake, ROOT, facts.Facts(host=HERE))
    return workflow.execute(
        resolved, shown, fake, ROOT, publisher or Publisher(), state_dir=state, host=HERE
    )


def _detach(att: Attachment, fake: FakeStack, pub: Publisher, state: Path) -> detach.DetachResult:
    """Detach the attachment as saved: with the storage the plan pinned."""
    saved = config.load(att.name, state)
    return detach.detach(saved, fake, pub, host=HERE, state_dir=state)


def _codes(p: plan.Plan) -> dict[str, str]:
    return {f.code: f.message for f in p.findings}


# ------------------------------------------------------------------------ the option


def test_the_option_is_recorded_in_the_attachment_and_excludes_runtime_only(bundle, tmp_path):
    att = _att(bundle)
    assert att.persist == "remote-schema-file"
    config.save(att, tmp_path)
    assert config.load(att.name, tmp_path).persist == "remote-schema-file"
    with pytest.raises(AttachmentError, match="exclude each other"):
        _att(bundle, runtime_only=True)


def test_a_saved_attachment_is_not_switched_by_a_later_flag(bundle, tmp_path):
    config.save(_att(bundle, remote_schema_file=False), tmp_path)
    given = workflow.Given(remote_schema_file=True)
    with pytest.raises(AttachmentError, match="--remote-schema-file"):
        workflow.resolve("pb-uat", given, ROOT, state_dir=tmp_path)


# ----------------------------------------------------------------------- preflight


def test_the_plan_asks_the_tickerplant_and_never_looks_here(bundle):
    assert not Path(STACK_PATH).exists()
    shown = plan.build(_att(bundle), _fake(), ROOT, facts.Facts(host=HERE))
    codes = _codes(shown)
    assert "PERSIST_UNAVAILABLE" not in codes
    assert codes["WILL_PERSIST"] == f"{STACK_PATH}: stp1 will append a marked block to it"
    (step,) = [c for c in shown.changes() if c["process"] == "schema file"]
    assert step["action"] == f"stp1 appends a marked block to {STACK_PATH}"


@pytest.mark.parametrize(
    ("setup", "said"),
    [
        (lambda f: f.stack_files.clear(), f"{STACK_PATH} does not exist on uat-box.example"),
        (lambda f: setattr(f, "stack_writable", False), "is not writable by stp1's user"),
        (lambda f: f.named("stp1").update(schemafile=""), "not started with -schemafile"),
        (
            lambda f: f.stack_files.update({STACK_PATH: b"/ GENERATED by uqf\n"}),
            "is generated",
        ),
    ],
)
def test_a_file_the_tickerplant_cannot_append_to_is_refused(bundle, setup, said):
    fake = _fake()
    setup(fake)
    shown = plan.build(_att(bundle), fake, ROOT, facts.Facts(host=HERE))
    assert not shown.ok
    assert said in _codes(shown)["PERSIST_UNAVAILABLE"]


def test_without_the_option_a_remote_stack_is_refused_with_both_ways_out(bundle):
    shown = plan.build(
        _att(bundle, remote_schema_file=False), _fake(), ROOT, facts.Facts(host=HERE)
    )
    (refused,) = [f for f in shown.findings if f.code == "PERSIST_UNAVAILABLE"]
    assert "this machine cannot edit it" in refused.message
    assert "--remote-schema-file" in refused.action and "--runtime-only" in refused.action
    assert "run uqs on the stack's machine" in refused.action


# ---------------------------------------------------------- apply, verify, detach


def test_apply_has_the_tickerplant_append_the_block_and_journals_it(bundle, tmp_path):
    fake, att = _fake(), _att(bundle)
    out = _run(att, fake, tmp_path)
    assert out.ok, out.stages
    text = fake.stack_files[STACK_PATH].decode()
    assert text.startswith(STACK_TEXT)
    assert persist.begin_marker(att.name, Manifest.load(att.name, tmp_path).token) in text
    m = Manifest.load(att.name, tmp_path)
    (op,) = [o for o in m.operations if o.op == "schema_block"]
    assert (op.status, op.ownership) == ("done", "created")
    assert op.post["process"] == "stp1" and op.post["path"] == STACK_PATH
    assert op.pre["by"] == "stp1"
    checks = {c.name: c for c in out.verified.checks} if out.verified else {}
    held = checks["the schema file still holds this attachment's block, unchanged"]
    assert held.ok, held.detail


def test_re_applying_reads_the_block_back_through_the_tickerplant(bundle, tmp_path):
    fake, att = _fake(), _att(bundle)
    assert _run(att, fake, tmp_path).ok
    before = fake.stack_files[STACK_PATH]
    again = _run(att, fake, tmp_path, Publisher())
    assert again.ok, again.stages
    assert fake.stack_files[STACK_PATH] == before, "nothing appended twice"


def test_an_edited_block_fails_verify(bundle, tmp_path):
    fake, att = _fake(), _att(bundle)
    assert _run(att, fake, tmp_path).ok
    fake.stack_files[STACK_PATH] = fake.stack_files[STACK_PATH].replace(b"/ Added", b"/ added")
    r = verify.verify(att, fake, tmp_path, ROOT, HERE)
    (failed,) = [c for c in r.checks if not c.ok and "schema file" in c.name]
    assert f"the block in {STACK_PATH} on stp1 was edited" in failed.detail


def test_detach_before_publication_takes_the_block_out_through_the_tickerplant(bundle, tmp_path):
    fake, att = _fake(), _att(bundle)
    pub = Publisher()
    assert _run(att, fake, tmp_path, pub).ok
    result = _detach(att, fake, pub, tmp_path)
    assert result.outcome == "rolled_back", result.blockers
    assert fake.stack_files[STACK_PATH] == STACK_TEXT.encode(), "byte for byte as it was"
    assert ("schema_block", "removed") in [(s.op, s.outcome) for s in result.steps]


def test_detach_refuses_when_the_tickerplant_file_changed_outside_the_block(bundle, tmp_path):
    fake, att = _fake(), _att(bundle)
    pub = Publisher()
    assert _run(att, fake, tmp_path, pub).ok
    fake.stack_files[STACK_PATH] = b"/ a person's edit\n" + fake.stack_files[STACK_PATH]
    result = _detach(att, fake, pub, tmp_path)
    assert result.outcome == "refused"
    assert any("was changed outside the block" in b.reason for b in result.blockers)
    assert persist.begin_marker(att.name, "") in fake.stack_files[STACK_PATH].decode()


def test_detach_refuses_when_the_tickerplant_cannot_be_asked(bundle, tmp_path):
    fake, att = _fake(), _att(bundle)
    pub = Publisher()
    assert _run(att, fake, tmp_path, pub).ok
    fake.down.add(6000)
    with pytest.raises(AttachmentError, match="the stack cannot be read"):
        _detach(att, fake, pub, tmp_path)
    assert persist.begin_marker(att.name, "") in fake.stack_files[STACK_PATH].decode()


def test_a_change_computed_from_stale_text_is_refused_by_the_tickerplant(bundle):
    fake = _fake()
    stp = fake.named("stp1")
    file = RemoteFile(fake, Endpoint("stp1", "uat-box.example", stp["port"]), STACK_PATH)
    with pytest.raises(AttachmentError, match="the file changed since it was read"):
        file.append("not what it holds\n", "/ BEGIN uqs-attach a t\n/ END uqs-attach a\n", "a", "t")


@pytest.mark.parametrize(
    ("mark", "said"),
    [
        ("log", "an earlier log stp1_piggybank_general_ledger20261015T00000 holds 400 bytes"),
        ("hdb", "the HDB holds a partition of it"),
    ],
)
def test_publication_is_read_off_the_stacks_disk_by_the_tickerplant(bundle, tmp_path, mark, said):
    fake, att = _fake(), _att(bundle)
    pub = Publisher()
    assert _run(att, fake, tmp_path, pub).ok
    if mark == "log":
        name = "stp1_piggybank_general_ledger20261015T00000"
        fake.stack_logs.append({"name": name, "size": 400})
    else:
        fake.stack_partitions.add("/data/hdb")
    result = _detach(att, fake, pub, tmp_path)
    assert result.outcome == "detached" and any(said in r for r in result.evidence.reasons)
    assert persist.begin_marker(att.name, "") in fake.stack_files[STACK_PATH].decode(), "kept"
    (asked,) = [r for _, op, r in fake.calls if op == "disk_marks"]
    assert asked["dirs"] == ["/data/wdbhdb", "/data/hdb"] and asked["logdir"] == "/data/tplogs"
